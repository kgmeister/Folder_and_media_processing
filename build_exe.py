#!/usr/bin/env python3
"""
Builds dist/SecureMediaProcessor.exe - a single double-clickable Windows program (Python, Flet and all
libraries bundled; no installs needed). Used locally and by .github/workflows/build-windows.yml.

    pip install -r requirements.txt pyinstaller
    python build_exe.py

The commit the exe is built from is written into it (_build_info.py), so "Check for updates" can tell
whether a newer build exists.
"""
import os, subprocess, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
NAME = "SecureMediaProcessor"

def current_commit() -> str:
    if os.environ.get("GITHUB_SHA"):
        return os.environ["GITHUB_SHA"]
    r = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ""

def main() -> int:
    commit = current_commit()
    dirty = subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain", "--untracked-files=no"],
                           capture_output=True, text=True).stdout.strip()
    if dirty and not os.environ.get("GITHUB_SHA"):
        print("Note: uncommitted changes are included in this build; its version id is the last commit.")
    (ROOT / "_build_info.py").write_text(
        f'"""Generated by build_exe.py - do not edit or commit."""\nCOMMIT = "{commit}"\n'
        f'BUILT = "{time.strftime("%Y-%m-%d %H:%M:%S")}"\n', encoding="utf-8")
    cmd = [sys.executable, "-m", "flet.cli", "pack", str(ROOT / "app.py"),
           "--name", NAME, "--icon", str(ROOT / "assets" / "icon.ico"),
           "--product-name", "Secure Media Processor",
           "--file-description", "Secure Media Processor - offline media privacy tool",
           "--product-version", commit[:7] or "dev", "--copyright", "kgmeister",
           "--hidden-import", "_build_info",
           "--distpath", str(ROOT / "dist"), "-y",
           "--",                                       # everything after this goes straight to PyInstaller
           "--collect-all=mozjpeg_lossless_optimization", f"--workpath={ROOT / 'build'}", f"--specpath={ROOT / 'build'}"]
    print(" ".join(cmd))
    r = subprocess.run(cmd, cwd=ROOT)
    exe = ROOT / "dist" / f"{NAME}.exe"
    if r.returncode != 0 or not exe.exists():
        print("Build failed.")
        return 1
    print(f"Built {exe} ({exe.stat().st_size / 1e6:.0f} MB) from commit {commit[:7] or 'unknown'}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
